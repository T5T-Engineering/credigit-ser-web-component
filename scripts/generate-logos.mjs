// Regenerates src/brand/logo-svgs.ts from the brand-kit SVGs.
// Brand colours are swapped for CSS variables so the default logo follows the active theme.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const src = join(root, "assets", "logos");
const files = {
  horizontal: "credigit-logo-horizontal.svg",
  stacked: "credigit-logo-stacked.svg",
  symbol: "credigit-symbol.svg",
  wordmark: "credigit-wordmark.svg",
};
const swaps = {
  "#0F1E2E": "var(--cg-logo-ink)",
  "#E8401C": "var(--cg-logo-accent)",
  "#5B6878": "var(--cg-logo-descriptor)",
};

const out = ["// Generated by scripts/generate-logos.mjs - do not edit by hand.", ""];
for (const [name, file] of Object.entries(files)) {
  let svg = readFileSync(join(src, file), "utf8").trim();
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
  svg = svg.replace(/(fill|stroke)="(#[0-9A-Fa-f]{6})"/g, (m, attr, hex) => {
    const v = swaps[hex.toUpperCase()];
    return v ? `style="${attr}:${v}"` : m;
  });
  const inner = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
  out.push(`export const ${name} = { viewBox: ${JSON.stringify(viewBox)}, markup: ${JSON.stringify(inner)} };`, "");
}
writeFileSync(join(root, "src", "brand", "logo-svgs.ts"), out.join("\n"));
console.log("logo-svgs.ts written");
